import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from 'node:module';
import fs from "node:fs";
import path from "node:path";

// ==================== Constants ====================

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
const outDir = "dist";

/** Entry point of npm package `buffer`. Uses alias to avoid importing directly from "buffer" which triggers node built-in warnings. */
const bufferPolyfillEntry = path.join(process.cwd(), "node_modules", "buffer", "index.js");

// Path constants
const cssRoot = path.join(process.cwd(), 'src');
const cssDest = path.join(process.cwd(), outDir, 'styles.css');

// ==================== Utility Functions ====================
// Recursively collects all CSS files under src/
function collectCssFiles(dir) {
	const results = [];
	if (!fs.existsSync(dir)) return results;
	const entries = fs.readdirSync(dir, { withFileTypes: true });
	for (const entry of entries) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			results.push(...collectCssFiles(full));
		} else if (entry.isFile() && entry.name.endsWith('.css')) {
			results.push(full);
		}
	}
	return results;
}

/**
 * Converts vinyl UI assets (WebP/PNG) under src/assets into data URLs and injects CSS into styles.css (not main.js).
 */
function buildVinylEmbeddedCssFragment() {
	const assetsDir = path.join(process.cwd(), "src", "assets");
	const discWebp = path.join(assetsDir, "disc.webp");
	const discPng = path.join(assetsDir, "disc.png");
	const needleWebp = path.join(assetsDir, "needle.webp");
	const needlePng = path.join(assetsDir, "needle.png");

	const rules = [];

	if (fs.existsSync(discWebp)) {
		const b64 = fs.readFileSync(discWebp).toString("base64");
		rules.push(
			`.music-player .disc-background.disc-background-embedded{background-image:url("data:image/webp;base64,${b64}")}`,
		);
	} else if (fs.existsSync(discPng)) {
		const b64 = fs.readFileSync(discPng).toString("base64");
		rules.push(
			`.music-player .disc-background.disc-background-embedded{background-image:url("data:image/png;base64,${b64}")}`,
		);
	} else {
		console.warn(`⚠ Missing disc image (disc.webp or disc.png), vinyl disc image will not render`);
	}

	if (fs.existsSync(needleWebp)) {
		const b64 = fs.readFileSync(needleWebp).toString("base64");
		rules.push(
			`.music-player .needle-image.needle-image-embedded{background-image:url("data:image/webp;base64,${b64}")}`,
		);
	} else if (fs.existsSync(needlePng)) {
		const b64 = fs.readFileSync(needlePng).toString("base64");
		rules.push(
			`.music-player .needle-image.needle-image-embedded{background-image:url("data:image/png;base64,${b64}")}`,
		);
	} else {
		console.warn(`⚠ Missing needle image (needle.webp or needle.png), vinyl needle image will not render`);
	}

	return `/* vinyl assets: inlined from src/assets at build */\n${rules.join("\n")}\n`;
}

/** Removes obsolete PNG/WebP assets from dist after inlining into styles.css. */
function removeStaleVinylPngFromDist() {
	const dir = path.join(process.cwd(), outDir);
	for (const name of ["disc.png", "needle.png", "disc.webp", "needle.webp"]) {
		const p = path.join(dir, name);
		try {
			if (fs.existsSync(p)) fs.unlinkSync(p);
		} catch (e) {
			console.warn(`⚠ Unable to remove stale artifact ${p}: ${e?.message ?? e}`);
		}
	}
}

// ==================== Build Functions ====================
// Builds CSS: combines all CSS files under src/ into dist/styles.css
async function buildCSS() {
	if (!fs.existsSync(cssRoot)) {
		console.warn('⚠ CSS root directory does not exist: src');
		return;
	}

	const cssFiles = collectCssFiles(cssRoot).sort();
	if (!cssFiles.length) {
		if (fs.existsSync(cssDest)) {
			fs.unlinkSync(cssDest);
			console.log('✓ Removed dist/styles.css (no CSS files in source directory)');
		}
		return;
	}

	const parts = cssFiles.map((file) => {
		const rel = path.relative(process.cwd(), file);
		const content = fs.readFileSync(file, 'utf8');
		return `/* ${rel} */\n${content}`;
	});
	const combinedCss = `${parts.join("\n\n")}\n\n${buildVinylEmbeddedCssFragment()}`;

	try {
		fs.mkdirSync(path.join(process.cwd(), outDir), { recursive: true });

		const result = await esbuild.transform(combinedCss, {
			loader: 'css',
			minify: prod,
			sourcemap: false,
		});

		fs.writeFileSync(cssDest, result.code);
	} catch (error) {
		console.error('Error building CSS, fell back to unminified version:', error);
		fs.writeFileSync(cssDest, combinedCss);
	}
}

/**
 * Replaces eval("require") in music-metadata with static require to avoid dynamic code execution warnings.
 */
function stripEvalRequireFromBundle() {
	const mainPath = path.join(process.cwd(), outDir, "main.js");
	if (!fs.existsSync(mainPath)) return;
	const code = fs.readFileSync(mainPath, "utf8");
	const next = code.replace(/eval\("require"\)/g, "require");
	if (next !== code) {
		fs.writeFileSync(mainPath, next);
	}
}

function stripEvalRequirePlugin() {
	return {
		name: "strip-eval-require",
		setup(build) {
			build.onEnd((result) => {
				if (result.errors.length > 0) return;
				stripEvalRequireFromBundle();
			});
		},
	};
}

// Copies manifest.json to output directory
function copyManifest() {
	const src = path.join(process.cwd(), 'manifest.json');
	const dest = path.join(process.cwd(), outDir, 'manifest.json');
	
	try {
		fs.mkdirSync(path.join(process.cwd(), outDir), { recursive: true });
		fs.copyFileSync(src, dest);
	} catch (e) {
		console.error('⚠ Failed to copy manifest.json:', e.message);
	}
}

// ==================== Watchers ====================
// Watches manifest.json changes with debounce
function watchManifest() {
	const manifestPath = path.join(process.cwd(), 'manifest.json');
	
	if (!fs.existsSync(manifestPath)) {
		return;
	}

	let copyTimer = null;
	let lastContent = fs.readFileSync(manifestPath, 'utf8');
	
	fs.watch(manifestPath, () => {
		if (copyTimer) {
			clearTimeout(copyTimer);
		}
		copyTimer = setTimeout(() => {
			try {
				const newContent = fs.readFileSync(manifestPath, 'utf8');
				if (newContent !== lastContent) {
					lastContent = newContent;
					copyManifest();
				}
			} catch (e) {
				console.error('⚠ Failed to read manifest.json:', e.message);
			}
			copyTimer = null;
		}, 100);
	});
}

// Watches CSS and image changes
function watchCSS() {
	if (!fs.existsSync(cssRoot)) {
		return;
	}

	let buildTimer = null;
	fs.watch(cssRoot, { recursive: true }, (eventType, filename) => {
		if (filename && (filename.endsWith(".css") || filename.endsWith(".png"))) {
			if (buildTimer) {
				clearTimeout(buildTimer);
			}
			buildTimer = setTimeout(() => {
				void buildCSS();
				buildTimer = null;
			}, 100);
		}
	});
}

// Create esbuild context
const context = await esbuild.context({
	banner: {
		js: banner,
	},
	plugins: [stripEvalRequirePlugin()],
	entryPoints: ["src/main.ts"],
	bundle: true,
	alias: {
		"buffer-polyfill": bufferPolyfillEntry,
	},
	loader: {
		'.ts': 'ts',
		'.tsx': 'tsx',
		'.json': 'json',
		'.css': 'empty', // CSS is handled via buildCSS
	},
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		// Do not externalize process / string_decoder / buffer / events so mobile builds bundle them properly
		...builtinModules.filter((m) => m !== 'process' && m !== 'string_decoder' && m !== 'buffer' && m !== 'events')
	],
	format: 'cjs',
	target: 'es2018',
	logLevel: "info",
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outdir: "dist",
	minify: prod,
	...(prod ? { drop: ['console', 'debugger'] } : {}),
});

// ==================== Main Execution ====================
async function main() {
	await buildCSS();
	copyManifest();

	if (prod) {
		await context.rebuild();
		// Copy built artifacts to project root for BRAT and direct git clone vault compatibility
		const distMain = path.join(process.cwd(), outDir, "main.js");
		const distCss = path.join(process.cwd(), outDir, "styles.css");
		const rootMain = path.join(process.cwd(), "main.js");
		const rootCss = path.join(process.cwd(), "styles.css");
		if (fs.existsSync(distMain)) fs.copyFileSync(distMain, rootMain);
		if (fs.existsSync(distCss)) fs.copyFileSync(distCss, rootCss);
		process.exit(0);
	} else {
		watchManifest();
		watchCSS();
		await context.watch();
	}
}

main().catch((error) => {
	console.error('Build failed:', error);
	process.exit(1);
});
