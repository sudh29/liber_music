/**
 * Music library type definitions
 * 
 * Defines data structures used to display library items in React components.
 */

import type { SmartPlaylistDefinition } from "./settings";

/**
 * Track presentation model for UI components
 */
export interface ReactTrackInfo {
	/** Music file path */
	path: string;
	/** Track title */
	title: string;
	/** Artist name */
	artist: string;
	/** Album name (optional) */
	album?: string;
	/** Cover image URL (optional) */
	coverUrl?: string;
	/** Track duration in seconds (optional) */
	duration?: number;
	/** User star rating (0 to 5) */
	rating?: number;
	/** Release year (optional) */
	year?: number;
	/** Genre (optional) */
	genre?: string;
	/** Track number (optional) */
	track?: number;
}

/**
 * Playlist representation model in library snapshot
 */
export interface ReactPlaylistGroup {
	/** Playlist display name */
	name: string;
	/** Tracks in playlist */
	tracks: ReactTrackInfo[];
	/** True if this playlist is dynamically evaluated from smart rules */
	isSmart?: boolean;
	/** True if this playlist is auto-synchronized from a vault folder */
	isFolder?: boolean;
	/** Smart playlist definition if isSmart is true */
	smartDefinition?: SmartPlaylistDefinition;
}

/**
 * Music library state snapshot
 * 
 * Generated by SnapshotService and supplied via useLibraryState hook.
 */
export interface ReactLibrarySnapshot {
	/** All library tracks */
	allTracks: ReactTrackInfo[];
	/** Favorite tracks */
	favorites: ReactTrackInfo[];
	/** Playlists array with names and associated tracks */
	playlists: ReactPlaylistGroup[];
	/** Artist groupings */
	artists: Array<{ name: string; tracks: ReactTrackInfo[] }>;
	/** Album groupings */
	albums: Array<{ name: string; tracks: ReactTrackInfo[] }>;
	/** Active playing track path */
	currentPath: string | null;
	/** Current list identifier (e.g. "all", "favorites", "playlist:xxx") */
	currentList: string | undefined;
}
